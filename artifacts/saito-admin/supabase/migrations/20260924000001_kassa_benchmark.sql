-- The drawer state-machine trigger (predates 'paused'): allow open->paused
-- ("count this drawer later") and paused->closed (finalize). Original
-- open->closed and the reopen-gated closed->open are preserved verbatim.
CREATE OR REPLACE FUNCTION trg_cash_drawer_state_guard() RETURNS trigger AS $$
BEGIN
  IF TG_OP = 'UPDATE' AND NEW.status IS DISTINCT FROM OLD.status THEN
    IF OLD.status = 'open' AND NEW.status = 'closed' THEN
      NULL; -- legal
    ELSIF OLD.status = 'closed' AND NEW.status = 'open' THEN
      IF COALESCE(current_setting('app.drawer_reopen', true), '') <> 'true' THEN
        RAISE EXCEPTION 'ILLEGAL_DRAWER_TRANSITION: closed->open only via reopen_cash_register'
          USING ERRCODE = 'P0001';
      END IF;
    ELSIF OLD.status = 'open' AND NEW.status = 'paused' THEN
      NULL; -- legal (2026-09-23 owner: "count this drawer later" / multi-drawer)
    ELSIF OLD.status = 'paused' AND NEW.status = 'closed' THEN
      NULL; -- legal (2026-09-23 owner: finalize the paused count)
    ELSE
      RAISE EXCEPTION 'ILLEGAL_DRAWER_TRANSITION: % -> %', OLD.status, NEW.status
        USING ERRCODE = 'P0001';
    END IF;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- 2026-09-23 (E2E gap): order_number was never generated by the /api/orders
-- path (new orders displayed UUID fragments). Race-free per-day sequences
-- per (prefix, location) via advisory lock. Seeded from existing numbers
-- (#D/#A/ORD- formats) so no collisions.
CREATE TABLE IF NOT EXISTS order_number_sequences (
  prefix text NOT NULL,
  location_id uuid NOT NULL,
  last_num integer NOT NULL DEFAULT 0,
  PRIMARY KEY (prefix, location_id)
);

CREATE OR REPLACE FUNCTION next_order_number(p_prefix text, p_location uuid) RETURNS text
LANGUAGE plpgsql AS $$
DECLARE
  v_num integer;
BEGIN
  PERFORM pg_advisory_xact_lock(hashtext(p_prefix || p_location::text));
  INSERT INTO order_number_sequences (prefix, location_id, last_num)
  VALUES (p_prefix, p_location, 1)
  ON CONFLICT (prefix, location_id)
  DO UPDATE SET last_num = order_number_sequences.last_num + 1
  RETURNING last_num INTO v_num;
  RETURN p_prefix || lpad(v_num::text, 3, '0');
END;
$$;

-- AUDIT §4.4: payment rows in the drawer log carry no staff attribution
-- (the frozen payment RPC writes them without created_by). Backfill from the
-- session's opener — BEFORE INSERT, only touches NULL created_by.
CREATE OR REPLACE FUNCTION trg_cash_log_backfill_staff() RETURNS trigger AS $$
BEGIN
  IF NEW.created_by IS NULL AND NEW.type = 'payment' AND NEW.session_id IS NOT NULL THEN
    SELECT opened_by INTO NEW.created_by
    FROM cash_drawer_sessions WHERE id = NEW.session_id;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS trg_cash_log_backfill_staff ON cash_drawer_log;
CREATE TRIGGER trg_cash_log_backfill_staff
  BEFORE INSERT ON cash_drawer_log
  FOR EACH ROW EXECUTE FUNCTION trg_cash_log_backfill_staff();

-- AUDIT §4.5: card payments never reached the drawer log (the KART tile was
-- always 0). Mirror each captured card payment into the open/paused drawer's
-- log (type=card_payment, staff = payments.performed_by). Balance walks
-- deliberately EXCLUDE card_payment (cards never sit in the drawer).
-- Dry-run verified in-transaction (test session + fake card payment, rollback).
CREATE OR REPLACE FUNCTION trg_payment_card_to_drawer() RETURNS trigger AS $$
DECLARE
  v_loc uuid;
  v_session uuid;
BEGIN
  IF NEW.payment_method = 'card' AND NEW.status = 'captured' AND NOT COALESCE(NEW.is_refund, false) THEN
    SELECT location_id INTO v_loc FROM orders WHERE id = NEW.order_id;
    IF v_loc IS NOT NULL THEN
      SELECT id INTO v_session
      FROM cash_drawer_sessions
      WHERE location_id = v_loc AND status IN ('open', 'paused')
      ORDER BY opened_at DESC LIMIT 1;
      IF v_session IS NOT NULL THEN
        INSERT INTO cash_drawer_log (session_id, type, amount, description, order_id, created_by)
        VALUES (v_session, 'card_payment', NEW.amount, 'Kart ödənişi', NEW.order_id, NEW.performed_by);
      END IF;
    END IF;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS trg_payment_card_to_drawer ON payments;
CREATE TRIGGER trg_payment_card_to_drawer
  AFTER INSERT ON payments
  FOR EACH ROW EXECUTE FUNCTION trg_payment_card_to_drawer();

COMMIT;
